    ID_USUARIO        NUMBER(18) DEFAULT EDSR.SEQ_PORTAL_B2B_USUARIO.NEXTVAL NOT NULL,
    CORREO            VARCHAR2(150 CHAR) NOT NULL,
    NOMBRE_COMPLETO   VARCHAR2(200 CHAR) NOT NULL,
    VENDOR_NUMBER     VARCHAR2(50 CHAR) NOT NULL,
    PASSWORD          VARCHAR2(200 CHAR) NOT NULL,
