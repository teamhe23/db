CREATE SEQUENCE EDSR.SEQ_PORTAL_B2B_RECEPCION_OC_DTL
    START WITH 1
    INCREMENT BY 1
    NOCACHE
    NOCYCLE;
/

CREATE TABLE EDSR.PORTAL_B2B_RECEPCION_OC_DTL (
    ID_RECEPCION_OC_DTL      NUMBER(18) DEFAULT EDSR.SEQ_PORTAL_B2B_RECEPCION_OC_DTL.NEXTVAL NOT NULL,
    ID_RECEPCION_OC_HDR      NUMBER(18) NOT NULL,
    PRD_LVL_NUMBER           VARCHAR2(12 CHAR) NOT NULL,
    REQUESTED_QTY            NUMBER(12,0) NOT NULL,
    RECEIVED_QTY             NUMBER(12,0) NOT NULL,
    CONFIRMED_QTY            NUMBER(12,0) NOT NULL,
    CONSTRAINT PK_PB2B_RECEPCION_OC_DTL PRIMARY KEY (ID_RECEPCION_OC_DTL),
    CONSTRAINT FK_PB2B_RECEP_OC_DTL_HDR FOREIGN KEY (ID_RECEPCION_OC_HDR)
        REFERENCES EDSR.PORTAL_B2B_RECEPCION_OC_HDR (ID_RECEPCION_OC_HDR),
    CONSTRAINT CK_PB2B_RECEP_OC_DTL_REQ CHECK (REQUESTED_QTY >= 0),
    CONSTRAINT CK_PB2B_RECEP_OC_DTL_REC CHECK (RECEIVED_QTY >= 0),
    CONSTRAINT CK_PB2B_RECEP_OC_DTL_CONF CHECK (CONFIRMED_QTY >= 0),
    CONSTRAINT CK_PB2B_RECEP_OC_DTL_CONF_REC CHECK (CONFIRMED_QTY <= RECEIVED_QTY),
    CONSTRAINT CK_PB2B_RECEP_OC_DTL_CONF_REQ CHECK (CONFIRMED_QTY <= REQUESTED_QTY)
);
/

CREATE INDEX EDSR.IDX_PB2B_RECEPCION_OC_DTL_01
    ON EDSR.PORTAL_B2B_RECEPCION_OC_DTL (ID_RECEPCION_OC_HDR);
/

CREATE INDEX EDSR.IDX_PB2B_RECEPCION_OC_DTL_02
    ON EDSR.PORTAL_B2B_RECEPCION_OC_DTL (PRD_LVL_NUMBER);
/

