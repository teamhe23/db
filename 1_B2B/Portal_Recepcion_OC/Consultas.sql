WITH HDR_SPLIT AS (
    SELECT
        H.ROWID AS RID,
        H.VENDOR_NUMBER,
        H.NOTA_VENTA,
        H.PMG_PO_NUMBER AS PMG_PO_NUMBER_ORIGINAL,
        TRIM(REGEXP_SUBSTR(REPLACE(H.PMG_PO_NUMBER, ' ', ''), '[^,]+', 1, LEVEL)) AS NUMERO_OC,
        H.MENSAJE
    FROM EDSR.OC_HDR_LOAD H
    CONNECT BY REGEXP_SUBSTR(REPLACE(H.PMG_PO_NUMBER, ' ', ''), '[^,]+', 1, LEVEL) IS NOT NULL
       AND PRIOR H.ROWID = H.ROWID
       AND PRIOR SYS_GUID() IS NOT NULL
)
SELECT
    HS.VENDOR_NUMBER,
    HS.NOTA_VENTA,
    HS.PMG_PO_NUMBER_ORIGINAL,
    HS.NUMERO_OC,
    ES.PMG_STAT_NAME AS ESTADO,
    TO_CHAR(OC.PMG_ENTRY_DATE, 'DD/MM/YYYY HH24:MI:SS') AS FECHA_OC,
    HS.MENSAJE
FROM HDR_SPLIT HS
LEFT JOIN EDSR.PMGHDREE OC
       ON TRIM(OC.PMG_PO_NUMBER) = HS.NUMERO_OC
LEFT JOIN EDSR.PMGSTSCD ES
       ON ES.PMG_STAT_CODE = OC.PMG_STAT_CODE
ORDER BY /*HS.NOTA_VENTA, */HS.NUMERO_OC desc;    