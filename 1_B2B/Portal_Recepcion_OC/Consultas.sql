--Consulta OC
SELECT
    PMG_DTL.PMG_PO_NUMBER AS PMG_PO_NUMBER,
    HDR.VENDOR_NUMBER AS VENDOR_NUMBER,
    PRD.PRD_LVL_NUMBER AS PRD_LVL_NUMBER,
    PRD.PRD_FULL_NAME AS DESCRIPTION,
    PRD.COD_BAR AS CODIGO_BARRAS,
    PRD.VPC_CASE_PACK_ID  AS CASE_PACK,
    DTL.QUANTITY AS QUANTITY,
    PMG_DTL.PMG_RCV_SQTY AS PMG_RCV_SQTY,
    PMG_DTL.PMG_STATUS AS PMG_STATUS
FROM EDSR.OC_HDR_LOAD HDR
INNER JOIN EDSR.OC_DTL_LOAD DTL
    ON HDR.ID_AUDIT_OC = DTL.ID_AUDIT_OC
INNER JOIN EPMM.TPPRDMST PRD
    ON TRIM(PRD.PRD_LVL_NUMBER) = TRIM(DTL.PRD_LVL_NUMBER)
INNER JOIN EPMM.PMGDTLEE PMG_DTL
    ON PMG_DTL.PMG_PO_NUMBER = '102503'
   AND PMG_DTL.PRD_LVL_CHILD = PRD.PRD_LVL_CHILD
WHERE INSTR(',' || HDR.PMG_PO_NUMBER || ',', ',' || '102503' || ',') > 0
  AND TRIM(HDR.VENDOR_NUMBER) = TRIM('1790476286001')
;

