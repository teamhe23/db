SELECT * FROM EDSRCT2.PIV_TRX_BCT_ITEM WHERE HEADID = 93157;

SELECT
    ITEM.SKU AS codigoPrincipal,
    ITEM.PRODUCTNAME AS descripcion,
    TO_NUMBER(ITEM.QUANTITY,'9999.99') AS cantidad,
    ROUND(NVL(ITEM.PRICE/( (IVA.PORC_IVA/100) + 1 ),0.00),2) AS precioUnitario,
    ROUND(NVL(DSCTO.AMOUNT/( (IVA.PORC_IVA/100) + 1 ),0.00),2) AS descuento,
    ROUND(NVL( ITEM.QUANTITY*(ITEM.PRICE/( (IVA.PORC_IVA/100) + 1 )) - ROUND(NVL(DSCTO.AMOUNT/( (IVA.PORC_IVA/100) + 1 ),0.00),2), 0.00) ,2) AS precioTotalSinImpuesto,
    2 AS codigo,
    IVA.COD_IVA AS codigoPorcentaje,
    DECODE(IVA.PORC_IVA,0.00,'0.00',TRIM(TO_CHAR(IVA.PORC_IVA,'999.99'))) AS tarifa,
    ROUND(NVL( ITEM.QUANTITY*(ITEM.PRICE/( (IVA.PORC_IVA/100) + 1 )) - ROUND(NVL(DSCTO.AMOUNT/( (IVA.PORC_IVA/100) + 1 ),0.00),2), 0.00) ,2) AS baseImponible,
    ROUND( (NVL( ITEM.QUANTITY*(ITEM.PRICE/( (IVA.PORC_IVA/100) + 1 )) - ROUND(NVL(DSCTO.AMOUNT/( (IVA.PORC_IVA/100) + 1 ),0.00),2), 0.00))*(IVA.PORC_IVA/100)  ,2) AS valor
FROM EDSRCT2.PIV_TRX_BCT_ITEM ITEM
    INNER JOIN EDSRCT2.SRI_IVA_PORCENTAJE IVA ON IVA.ID_IVA = ITEM.ID_IVA
    INNER JOIN  EDSRCT2.PIV_TRX_BCT_HEAD HEAD ON HEAD.HEADID = ITEM.HEADID
    INNER JOIN EDSR.PIVOT_COMPANY COM ON HEAD.COMPANY = COM.COD_COMPANY
    INNER JOIN EDSR.PIVOT_ESTABLECIMIENTO EST ON (HEAD. BRANCHID = EST.BRANCHID AND COM.COD_COMPANY = EST.COD_COMPANY)
    LEFT JOIN EDSRCT2.PIV_TRX_BCT_DSCTO  DSCTO  ON (HEAD.HEADID = DSCTO.HEADID AND ITEM.SEQUENCE = DSCTO.ITEMSEQUENCE)
WHERE
    COM.COD_COMPANY = 'HE'
    AND HEAD.HEADID = 93364;

--TotalConImpuestos
SELECT
    2 AS codigo,
    IVA.COD_IVA AS codigoPorcentaje,
    IVA.PORC_IVA AS tarifa,
    ROUND(NVL( SUM( (ITEM.QUANTITY * ITEM.PRICE) /( (IVA.PORC_IVA/100) + 1 ) - ROUND(NVL(DSCTO.AMOUNT/( (IVA.PORC_IVA/100) + 1 ),0.00),2) ), 0.00) ,2) AS baseImponible,
	ROUND( (NVL( SUM( (ITEM.QUANTITY * ITEM.PRICE) /( (IVA.PORC_IVA/100) + 1 ) - ROUND(NVL(DSCTO.AMOUNT/( (IVA.PORC_IVA/100) + 1 ),0.00),2) ), 0.00))*(IVA.PORC_IVA/100) ,2) AS valor	
FROM EDSRCT2.PIV_TRX_BCT_ITEM ITEM
    INNER JOIN EDSRCT2.SRI_IVA_PORCENTAJE IVA ON IVA.ID_IVA = ITEM.ID_IVA
    INNER JOIN  EDSRCT2.PIV_TRX_BCT_HEAD HEAD ON HEAD.HEADID = ITEM.HEADID
    INNER JOIN EDSR.PIVOT_COMPANY COM ON HEAD.COMPANY = COM.COD_COMPANY
    INNER JOIN EDSR.PIVOT_ESTABLECIMIENTO EST ON (HEAD. BRANCHID = EST.BRANCHID AND COM.COD_COMPANY = EST.COD_COMPANY)
    LEFT JOIN EDSRCT2.PIV_TRX_BCT_DSCTO  DSCTO  ON (HEAD.HEADID = DSCTO.HEADID AND ITEM.SEQUENCE = DSCTO.ITEMSEQUENCE)
WHERE
    COM.COD_COMPANY = 'HE'
    AND HEAD.HEADID = 93364
GROUP BY IVA.COD_IVA,IVA.PORC_IVA--,ITEM.SKU
