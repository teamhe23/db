SELECT
			pic.id_picking,
		    COM.RAZON_SOCIAL as razonSocial,
		    'PROMART' AS nombreComercial,
		    COM.RUC AS ruc,
		    '01' codDoc,
		    REGEXP_SUBSTR(HEAD.PPLSERIALNUMBER, '[^-]+',1,1) AS estab,
		    REGEXP_SUBSTR(HEAD.PPLSERIALNUMBER, '[^-]+',1,2) AS ptoEmi,
		    REGEXP_SUBSTR(HEAD.PPLSERIALNUMBER, '[^-]+',1,3) AS secuencial,
		    COM.DIRECCION_MATRIZ AS dirMatriz,
		    TO_CHAR(HEAD.TRXDATE,'DD/MM/YYYY') AS fechaEmision,
		    EST.VC_DIRECCION AS dirEstablecimiento,
		    'SI' AS obligadoContabilidad,
		    CASE
		        WHEN HEAD.CUSTOMERBUSINESSDOCNUMBER IS NULL THEN '05'
		        WHEN LENGTH(HEAD.CUSTOMERBUSINESSDOCNUMBER) = 0 THEN '05'
		        ELSE '04'
		    END AS tipoIdentificacionComprador,
		    CASE
		        WHEN HEAD.CUSTOMERBUSINESSDOCNUMBER IS NULL THEN HEAD.CUSTOMERNAME || ' ' || HEAD.CUSTOMERSURNAME
		        WHEN LENGTH(HEAD.CUSTOMERBUSINESSDOCNUMBER) = 0 THEN  HEAD.CUSTOMERNAME || ' ' || HEAD.CUSTOMERSURNAME
		        ELSE HEAD.CUSTOMERBUSINESSNAME
		    END AS razonSocialComprador,
		    CASE
		        WHEN HEAD.CUSTOMERBUSINESSDOCNUMBER IS NULL THEN HEAD.CUSTOMERDOCUMENTNUMBER
		        WHEN LENGTH(HEAD.CUSTOMERBUSINESSDOCNUMBER) = 0 THEN HEAD.CUSTOMERDOCUMENTNUMBER
		        ELSE HEAD.CUSTOMERBUSINESSDOCNUMBER
		    END AS identificacionComprador,
		    nvl(pic.direccion, 'SN') AS direccionComprador,
		    HEAD.AFFECTEDTOTALAMOUNT + HEAD.UNAFFECTEDTOTALAMOUNT AS totalSinImpuestos,
		    NVL('V_TOTALDESCUENTO',0.00) AS totalDescuento,
		    2 AS codigo,
		    2 AS codigoPorcentaje,
		    HEAD.AFFECTEDTOTALAMOUNT AS baseImponible,
		    HEAD.IGVPERCENTAGE AS tarifa,
		    HEAD.IGVTOTALAMOUNT AS valor,
		    '0.00' AS propina,
		    HEAD.AMOUNT AS importeTotal,
		    'DOLAR' AS moneda,
		    MEDIOPAGO.COD_SRI AS formaPago,
		    HEAD.AMOUNT AS total,
		    PAYMENT.CUOTAS*30 AS plazo,
		    'dias' AS unidadTiempo,
		    HEAD.CUSTOMEREMAIL AS email,
		    HEAD.CUSTOMERPHONE AS telefono,
		    'Estimado cliente, de acuerdo al Art. 50 de la Ley de Regimen Tributario Interno, Los agentes de retencion estan obligados a entregar el respectivo comprobante de retencion, dentro del termino no mayor de cinco dias de recibido el comprobante de venta' AS disclaimer
		FROM EDSRCT2.PIV_TRX_BCT_HEAD HEAD
			INNER JOIN EDSR.PIVOT_COMPANY COM ON HEAD.COMPANY = COM.COD_COMPANY
			INNER JOIN EDSR.PIVOT_ESTABLECIMIENTO EST ON (HEAD.BRANCHID = EST.BRANCHID AND COM.COD_COMPANY = EST.COD_COMPANY)
			LEFT JOIN EDSRCT2.PIV_TRX_BCT_DSCTO  DSCTO  ON HEAD.HEADID = DSCTO.HEADID
			LEFT JOIN EDSRCT2.PIV_TRX_BCT_PAYMENT PAYMENT ON PAYMENT.HEADID = HEAD.HEADID
			LEFT JOIN EDSR.HP_VTEX_MEDIO_PAGO MEDIOPAGO ON MEDIOPAGO.IDVTEX = PAYMENT.PAYMENTMETHODCODE
    		LEFT JOIN edsr.hp_vtex_picking pic on pic.id_picking = head.originid and head.origintrx = 1
		WHERE
		    COM.COD_COMPANY = 'HE'
		   -- AND PAYMENT.PAYMENTMETHODCODE IN (1,401,2,3,4,5)
		    AND HEAD.HEADID = 15422;
